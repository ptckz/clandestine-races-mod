-- Testes do módulo spots: locais de largada criados pelo admin e seus percursos.

local spots = require("clandestine.spots")

local function pt(x, y)
	return { x = x, y = y, z = 50 }
end

T.test("store começa vazio", function()
	local s = spots.new()
	T.eq(#spots.list(s), 0)
end)

T.test("adicionar um local com nome válido retorna id", function()
	local s = spots.new()
	local r = spots.add(s, "Valentine", pt(10, 20))
	T.eq(r.ok, true)
	T.eq(r.id, 1)
	T.eq(#spots.list(s), 1)
end)

T.test("nome vazio ou não texto é rejeitado", function()
	local s = spots.new()
	T.eq(spots.add(s, "", pt(0, 0)).reason, "invalid_name")
	T.eq(spots.add(s, "   ", pt(0, 0)).reason, "invalid_name")
	T.eq(spots.add(s, nil, pt(0, 0)).reason, "invalid_name")
end)

T.test("nome repetido é rejeitado, ignorando maiúsculas", function()
	local s = spots.new()
	spots.add(s, "Valentine", pt(0, 0))
	T.eq(spots.add(s, "valentine", pt(5, 5)).reason, "duplicate_name")
	T.eq(#spots.list(s), 1)
end)

T.test("coordenada não numérica é rejeitada", function()
	local s = spots.new()
	T.eq(spots.add(s, "A", { x = "10", y = 0, z = 0 }).reason, "invalid_point")
	T.eq(spots.add(s, "A", { x = 0, y = 0 }).reason, "invalid_point")
end)

T.test("ponto fora dos limites do mapa é rejeitado", function()
	local s = spots.new({ minX = -100, maxX = 100, minY = -100, maxY = 100, minZ = -50, maxZ = 500 })
	T.eq(spots.add(s, "Fora", { x = 101, y = 0, z = 0 }).reason, "out_of_bounds")
	T.eq(spots.add(s, "Fora", { x = 0, y = -101, z = 0 }).reason, "out_of_bounds")
	T.eq(spots.add(s, "Fora", { x = 0, y = 0, z = 501 }).reason, "out_of_bounds")
	T.eq(spots.add(s, "Dentro", { x = 100, y = -100, z = 500 }).ok, true, "bordas são válidas")
end)

T.test("remover um local pelo id", function()
	local s = spots.new()
	local a = spots.add(s, "A", pt(0, 0))
	spots.add(s, "B", pt(1, 1))
	T.eq(spots.remove(s, a.id).ok, true)
	local list = spots.list(s)
	T.eq(#list, 1)
	T.eq(list[1].name, "B")
end)

T.test("remover id inexistente retorna not_found", function()
	local s = spots.new()
	T.eq(spots.remove(s, 99).reason, "not_found")
end)

T.test("list devolve os locais em ordem de criação", function()
	local s = spots.new()
	spots.add(s, "C", pt(0, 0))
	spots.add(s, "A", pt(1, 1))
	spots.add(s, "B", pt(2, 2))
	local list = spots.list(s)
	T.eq(list[1].name, "C")
	T.eq(list[2].name, "A")
	T.eq(list[3].name, "B")
end)

T.test("adicionar percurso: pontos são guardados na ordem", function()
	local s = spots.new()
	local a = spots.add(s, "Largada", pt(0, 0))
	T.eq(spots.addCheckpoint(s, a.id, pt(100, 0)).ok, true)
	T.eq(spots.addCheckpoint(s, a.id, pt(200, 0)).ok, true)
	local route = spots.get(s, a.id).route
	T.eq(#route, 2)
	T.eq(route[1].x, 100)
	T.eq(route[2].x, 200)
end)

T.test("checkpoint fora dos limites não entra no percurso", function()
	local s = spots.new({ minX = -100, maxX = 100, minY = -100, maxY = 100, minZ = -50, maxZ = 500 })
	local a = spots.add(s, "Largada", pt(0, 0))
	T.eq(spots.addCheckpoint(s, a.id, pt(500, 0)).reason, "out_of_bounds")
	T.eq(#spots.get(s, a.id).route, 0)
end)

T.test("checkpoint em local inexistente retorna not_found", function()
	local s = spots.new()
	T.eq(spots.addCheckpoint(s, 42, pt(0, 0)).reason, "not_found")
end)

T.test("percurso só fica pronto com pelo menos 2 pontos", function()
	local s = spots.new()
	local a = spots.add(s, "Largada", pt(0, 0))
	T.falsy(spots.isReady(spots.get(s, a.id)))
	spots.addCheckpoint(s, a.id, pt(100, 0))
	T.falsy(spots.isReady(spots.get(s, a.id)))
	spots.addCheckpoint(s, a.id, pt(200, 0))
	T.truthy(spots.isReady(spots.get(s, a.id)))
end)

T.test("get de id inexistente devolve nil", function()
	local s = spots.new()
	T.eq(spots.get(s, 1), nil)
end)

T.test("o local guarda o nome informado", function()
	local s = spots.new()
	local a = spots.add(s, "  Blackwater  ", pt(0, 0))
	T.eq(spots.get(s, a.id).name, "Blackwater")
end)
