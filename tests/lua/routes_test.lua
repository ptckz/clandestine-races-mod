-- Testes do módulo routes: pontos nomeados marcados pelo admin, ordem, gravação e leitura.

local routes = require("clandestine.routes")

local NAMES = { "Thieves Landing", "Blackwater", "Cattail Pond" }

local function pt(x, y)
	return { x = x, y = y, z = 40 }
end

T.test("rota nova tem os pontos na ordem e nenhum marcado", function()
	local r = routes.new(1, "Rota A", NAMES)
	T.eq(#r.slots, 3)
	T.eq(r.slots[1].name, "Thieves Landing")
	T.eq(r.slots[3].name, "Cattail Pond")
	local marked, total = routes.progress(r)
	T.eq(marked, 0)
	T.eq(total, 3)
	T.falsy(routes.isComplete(r))
end)

T.test("rota sem nome ou com menos de 2 pontos é rejeitada", function()
	T.errors(function() routes.new(1, "", NAMES) end)
	T.errors(function() routes.new(1, "A", { "Só um" }) end)
	T.errors(function() routes.new(1, "A", nil) end)
end)

T.test("marcar um ponto guarda a posição e conta no progresso", function()
	local r = routes.new(1, "Rota A", NAMES)
	T.eq(routes.setPoint(r, 2, pt(10, 20)).ok, true)
	T.eq(r.slots[2].point.x, 10)
	local marked = routes.progress(r)
	T.eq(marked, 1)
end)

T.test("ponto inválido ou posição inexistente é recusado", function()
	local r = routes.new(1, "Rota A", NAMES)
	T.eq(routes.setPoint(r, 1, { x = "a", y = 0, z = 0 }).reason, "invalid_point")
	T.eq(routes.setPoint(r, 1, { x = 1, y = 2 }).reason, "invalid_point")
	T.eq(routes.setPoint(r, 9, pt(1, 1)).reason, "invalid_slot")
	T.eq(routes.progress(r), 0, "nada foi marcado")
end)

T.test("remarcar um ponto substitui o anterior", function()
	local r = routes.new(1, "Rota A", NAMES)
	routes.setPoint(r, 1, pt(1, 1))
	routes.setPoint(r, 1, pt(5, 5))
	T.eq(r.slots[1].point.x, 5)
	T.eq(routes.progress(r), 1)
end)

T.test("a rota só fica completa com todos os pontos marcados", function()
	local r = routes.new(1, "Rota A", NAMES)
	routes.setPoint(r, 1, pt(1, 1))
	routes.setPoint(r, 3, pt(3, 3))
	T.falsy(routes.isComplete(r))
	routes.setPoint(r, 2, pt(2, 2))
	T.truthy(routes.isComplete(r))
end)

T.test("points devolve a largada, as passagens obrigatórias e a chegada, na ordem", function()
	local r = routes.new(1, "Rota A", NAMES)
	routes.setPoint(r, 3, pt(300, 0))
	routes.setPoint(r, 1, pt(100, 0))
	routes.setPoint(r, 2, pt(200, 0))
	local list = routes.points(r)
	T.eq(#list, 3)
	T.eq(list[1].x, 100, "largada")
	T.eq(list[2].x, 200, "passagem obrigatória")
	T.eq(list[3].x, 300, "chegada")
end)

T.test("points recusa uma rota incompleta", function()
	local r = routes.new(1, "Rota A", NAMES)
	routes.setPoint(r, 1, pt(1, 1))
	T.errors(function() routes.points(r) end)
end)

T.test("points devolve cópias: mexer na lista não altera a rota", function()
	local r = routes.new(1, "Rota A", { "A", "B" })
	routes.setPoint(r, 1, pt(1, 1))
	routes.setPoint(r, 2, pt(2, 2))
	local list = routes.points(r)
	list[1].x = 999
	T.eq(r.slots[1].point.x, 1)
end)

T.test("a rota inicial é Thieves Landing, Blackwater, Cattail Pond, com Blackwater já preenchido", function()
	local list = routes.default()
	T.eq(#list, 1)
	local r = list[1]
	T.eq(r.slots[1].name, "Thieves Landing")
	T.eq(r.slots[2].name, "Blackwater")
	T.eq(r.slots[3].name, "Cattail Pond")
	T.eq(r.slots[1].point, nil, "largada ainda sem marcar")
	T.truthy(r.slots[2].point ~= nil, "Blackwater preenchido")
	T.eq(r.slots[3].point, nil, "chegada ainda sem marcar")
	T.falsy(routes.isComplete(r))
end)

T.test("gravar e ler devolve a mesma rota", function()
	local r = routes.new(7, "Rota \"A\"", NAMES)
	routes.setPoint(r, 1, pt(-1400.5, -2300.25))
	routes.setPoint(r, 2, pt(-798.984, -1247.722))
	local back = routes.parse(routes.serialize({ r }))
	T.truthy(back ~= nil, "leitura funcionou")
	T.eq(#back, 1)
	T.eq(back[1].id, 7)
	T.eq(back[1].name, "Rota \"A\"")
	T.near(back[1].slots[1].point.x, -1400.5, 0.001)
	T.near(back[1].slots[2].point.y, -1247.722, 0.001)
	T.eq(back[1].slots[3].point, nil, "ponto não marcado continua não marcado")
end)

T.test("ler texto inválido devolve nil e não executa código", function()
	T.eq(routes.parse("isto não é lua"), nil)
	T.eq(routes.parse("return 42"), nil)
	T.eq(routes.parse(nil), nil)
	-- Um texto que tenta usar funções do sistema não pode ter acesso a elas.
	local list = routes.parse("os.exit(1) return {}")
	T.eq(list, nil)
end)

T.test("ler rejeita rota com coordenada inválida", function()
	local src = 'return { { id = 1, name = "A", slots = { { name = "X", point = { x = "a", y = 1, z = 1 } }, { name = "Y" } } } }'
	T.eq(routes.parse(src), nil)
end)

T.test("serialize e parse mantêm várias rotas na ordem", function()
	local a = routes.new(1, "A", { "A1", "A2" })
	local b = routes.new(2, "B", { "B1", "B2", "B3" })
	local back = routes.parse(routes.serialize({ a, b }))
	T.eq(#back, 2)
	T.eq(back[1].name, "A")
	T.eq(back[2].name, "B")
	T.eq(#back[2].slots, 3)
end)
